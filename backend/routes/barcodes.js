const express = require('express');
const { body, param, query } = require('express-validator');
const auth = require('../middleware/auth');
const validate = require('../middleware/validate');
const { requireCapability } = require('../middleware/permissions');
const { asyncHandler } = require('../middleware/errorHandler');
const { audit } = require('../middleware/audit');
const service = require('../services/barcodes');
const router = express.Router();
router.use(require('../middleware/rateLimiters').barcodeLimiter, auth);
const code = (validator) => validator.trim().matches(/^99\d{16}$/).withMessage('Scan a pack label generated by this app (18 digits starting with 99).');

router.get('/batches', requireCapability('products.view'), [query('page').optional().isInt({ min: 1 }).toInt(), query('search').optional().trim().isLength({ max: 120 })], validate,
  asyncHandler(async (req, res) => res.json(await service.listBatches(req.businessId, req.query.page, req.query.search))));
router.get('/batches/:id', requireCapability('products.view'), [param('id').isUUID()], validate,
  asyncHandler(async (req, res) => res.json(await service.getBatch(req.params.id, req.businessId))));
router.post('/batches', requireCapability('transactions.create'), [
  body('requestId').isUUID(), body('product').isUUID(), body('count').isInt({ min: 1, max: 200 }).toInt(),
  body('quantity').isFloat({ min: 0.0001, max: 9999999999 }).toFloat(),
  body('mode').isIn(['prepare', 'receive', 'existing']),
  body('batchNumber').optional().trim().isLength({ max: 80 }),
  body('expiryDate').optional({ values: 'falsy' }).isDate({ format: 'YYYY-MM-DD', strictMode: true }),
], validate, asyncHandler(async (req, res) => {
  const result = await service.createBatch(req.body, req.businessId, req.user);
  if (!result.replayed) audit(req, 'CREATE_BARCODE_LABELS', 'BARCODE_BATCH', result.id, { count: result.labels.length, mode: req.body.mode, product: result.labels[0].productName });
  res.status(result.replayed ? 200 : 201).json(result);
}));
router.get('/labels/:code', requireCapability('products.view'), [code(param('code'))], validate,
  asyncHandler(async (req, res) => res.json(await service.readLabel(req.params.code, req.businessId))));
router.post('/scan', requireCapability('transactions.create'), [
  body('requestId').isUUID(), code(body('code')), body('mode').isIn(['stock_in', 'stock_out']),
  body('station').optional().trim().isLength({ max: 120 }), body('customer').optional().trim().isLength({ max: 120 }),
  body('paymentType').optional().isIn(['cash','credit']),body('customerId').optional({values:'falsy'}).isUUID(),
  body('dueDate').optional({values:'falsy'}).isDate({format:'YYYY-MM-DD',strictMode:true}),
], validate, asyncHandler(async (req, res) => {
  const result = await service.scanLabel(req.body, req.businessId, req.user);
  if (!result.replayed) audit(req, 'SCAN_BARCODE', 'TRANSACTION', result.transaction.id, { code: result.label.code, type: result.mode, quantity: result.label.quantity, station: req.body.station || '' });
  res.status(result.replayed ? 200 : 201).json(result);
}));
module.exports = router;
