const { test, expect } = require('@playwright/test');

test('supplier ledger receives stock, records credit and payments, and reverses mistakes', async ({ page, isMobile }, info) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/login');
  await page.getByLabel('Email address').fill('browser-admin@example.test');
  await page.getByLabel(/^Password/).fill('Browser-password-42');
  const settingsReady = page.waitForResponse(response => response.url().endsWith('/api/settings') && response.ok());
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/$/);
  await settingsReady;
  await page.goto('/suppliers');
  await page.getByRole('button', { name: 'Add supplier', exact: true }).first().click();
  const name = `Supplier ${info.project.name} ${Date.now()}`;
  await page.getByLabel('Supplier name').fill(name);
  await page.getByText('Already owe this supplier?', { exact: true }).click();
  await page.getByLabel('Existing balance').fill('1000');
  await page.getByRole('button', { name: 'Add supplier', exact: true }).last().click();
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await expect(page.locator('.credit-account-balance strong')).toContainText('1,000');
  await page.getByRole('button', { name: 'Receive a purchase', exact: true }).click();
  await page.getByRole('button', { name: /^Product/ }).click();
  await page.getByRole('option', { name: /Premium Basmati/ }).click();
  await page.getByLabel(/^Quantity/).fill('10');
  await page.getByLabel('Cost per unit').fill('10');
  await page.getByLabel('Paid now').fill('20');
  await page.getByLabel('Payment due date').fill('2030-01-01');
  await page.getByLabel('Supplier bill reference').fill('SUPPLIER-PURCHASE-100');
  await page.getByRole('button', { name: 'Receive stock and record bill', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.credit-account-balance strong')).toContainText('1,080');
  await expect(page.locator('.supplier-statement')).toContainText('SUPPLIER-PURCHASE-100');
  await page.getByRole('button', { name: 'Record payment', exact: true }).click();
  await page.getByLabel('Amount paid').fill('80');
  await page.getByRole('button', { name: 'Payment method' }).click();
  await page.getByRole('option', { name: 'Bank transfer', exact: true }).click();
  await page.getByLabel('Reference', { exact: true }).fill('SUPPLIER-BANK-80');
  await page.getByRole('button', { name: 'Record supplier payment', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.credit-account-balance strong')).toContainText('1,000');
  await expect(page.locator('.supplier-statement')).toContainText('SUPPLIER-BANK-80');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  if (!isMobile) {
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export statement', exact: true }).click();
    const file = await download;
    expect(file.suggestedFilename()).toMatch(/statement.*\.pdf$/);
    await file.saveAs(`test-results/supplier-statement-${info.project.name}.pdf`);
  }
  await page.getByText('Correct an entry', { exact: true }).click();
  await page.locator('.supplier-corrections li').filter({ hasText: 'Rs. 80.00' }).getByRole('button', { name: 'Reverse', exact: true }).click();
  await page.getByLabel('Reason for reversal').fill('Wrong payment reference');
  await page.getByRole('button', { name: 'Reverse entry', exact: true }).click();
  await expect(page.locator('.credit-account-balance strong')).toContainText('1,080');
  await page.getByRole('button', { name: 'Edit supplier', exact: true }).click();
  await page.getByLabel('Supplier name').fill(`${name} updated`);
  await page.getByRole('button', { name: 'Save supplier', exact: true }).click();
  await expect(page.getByRole('heading', { name: `${name} updated`, exact: true })).toBeVisible();
  await page.screenshot({ path: `test-results/supplier-${info.project.name}.png`, fullPage: true });
  await page.evaluate(() => { localStorage.setItem('rim.theme', 'dark'); localStorage.setItem('rim.language', 'ur'); });
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await expect(page.locator('.credit-account')).toContainText('سپلائر کی تفصیل بدلیں');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `test-results/supplier-urdu-${info.project.name}.png`, fullPage: true });
  expect(errors).toEqual([]);
});
